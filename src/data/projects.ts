/**
 * Look up a project by slug. Returns undefined if not found.
 */
export function getProjectBySlug(slug: string): Project | undefined {
  return projects.find((p) => p.slug === slug);
}

/**
 * Filter projects by neighborhood (e.g., "Paradise Valley").
 */
export function getProjectsByNeighborhood(neighborhood: string): Project[] {
  return projects.filter((p) => p.neighborhood === neighborhood);
}

/**
 * Filter projects by category (e.g., "Kitchen", "Bathroom", "Living",
 * "Outdoor", "Whole-Home").
 */
export function getProjectsByCategory(category: string): Project[] {
  return projects.filter((p) => p.category === category);
}

/**
 * All slugs — useful for generateStaticParams in dynamic routes.
 */
export function getAllSlugs(): string[] {
  return projects.map((p) => p.slug);
}
